function fill(s, vars) {
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m)) : s;
}
function t(key, vars) {
  const s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return fill(s, vars);
}
// Çoğul: İngilizce n === 1 için ".one", diğerleri ".other"; Türkçe her sayı için ".other". {n} otomatik doldurulur.
function tn(key, n, vars) {
  const form = LANG === 'tr' || n !== 1 ? 'other' : 'one';
  return t(key + '.' + form, { n, ...vars });
}

function applyI18n(root = document) {
  for (const n of root.querySelectorAll('[data-i18n]')) n.textContent = t(n.dataset.i18n);
  for (const n of root.querySelectorAll('[data-i18n-title]')) n.title = t(n.dataset.i18nTitle);
  for (const n of root.querySelectorAll('[data-i18n-placeholder]')) n.placeholder = t(n.dataset.i18nPlaceholder);
  for (const n of root.querySelectorAll('[data-i18n-aria]')) n.setAttribute('aria-label', t(n.dataset.i18nAria));
}

// Dili değiştirir: tercih bu cihazda (localStorage) tutulur, arka plan betiği için storage.local'a da yazılır; sonra sayfa yenilenir.
function setLang(v) {
  try { localStorage.setItem('lang', v); } catch { /* depolama yoksa sessizce geç */ }
  const x = (typeof browser !== 'undefined' && browser.runtime) ? browser : (typeof chrome !== 'undefined' ? chrome : null);
  const reload = () => location.reload();
  try {
    if (x && x.storage && x.storage.local) Promise.resolve(x.storage.local.set({ lang: v })).then(reload, reload);
    else reload();
  } catch { reload(); }
}

